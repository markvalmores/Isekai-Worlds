export function getTranslation(lang: LanguageCode, key: string): string {
  const dict = DICTIONARY[lang] || DICTIONARY.en;
  return dict[key] || DICTIONARY.en[key] || key;
}

// Call AI Translation API endpoint for dynamic custom text
export async function requestAiTranslation(texts: string[], targetLang: LanguageCode): Promise<string[]> {
  try {
    const langObj = SUPPORTED_LANGUAGES.find(l => l.code === targetLang);
    const targetLangName = langObj ? langObj.name : "Japanese";

    const res = await fetch("/api/translate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        targetLang: targetLangName,
        texts: texts
      })
    });
    const data = await res.json();
    if (data.translatedTexts && Array.isArray(data.translatedTexts)) {
      return data.translatedTexts;
    }
  } catch (err) {
    console.error("AI Translation client error:", err);
  }
  return texts;
}
